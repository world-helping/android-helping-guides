import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(mobileRoot, '..');
const guidesDir = path.join(repoRoot, 'public', 'guides');
const outputFile = path.join(mobileRoot, 'lib', 'guideImages.ts');

function collectImages(dir, relativeDir = '') {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const images = [];

  for (const entry of entries) {
    const relativePath = path.join(relativeDir, entry.name);

    if (entry.isDirectory()) {
      images.push(...collectImages(path.join(dir, entry.name), relativePath));
      continue;
    }

    if (/\.(png|jpe?g|webp)$/i.test(entry.name)) {
      images.push(relativePath.replace(/\\/g, '/'));
    }
  }

  return images.sort();
}

const images = collectImages(guidesDir);
const lines = images.map((relativePath) => {
  const publicPath = `/guides/${relativePath}`;
  const requirePath = `../../public/guides/${relativePath}`;
  return `  "${publicPath}": require("${requirePath}"),`;
});

const content = `/* eslint-disable */
// Auto-generated by scripts/generate-guide-images.mjs — do not edit manually.

import type { ImageSourcePropType } from 'react-native';

export const guideImages: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};
`;

fs.writeFileSync(outputFile, content, 'utf8');
console.log(`Generated ${images.length} guide images → lib/guideImages.ts`);
